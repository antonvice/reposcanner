def test_sample_has_directory_breadth_tests_context_and_no_generated_code(tmp_path):
    repo = tmp_path / "repo"
    repo.mkdir()
    files = {
        "src/reports/DataSet.Designer.cs": "// <auto-generated>\n" + "public int Value;\n" * 10000,
        "src/budget/Rules.cs": "public int Value;\n" * 6000,
        "src/budget/OtherRules.cs": "public int Value;\n" * 5500,
        "src/api/Api.cs": "public int Value;\n" * 120,
        "src/storage/Storage.cs": "public int Value;\n" * 120,
        "tests/BudgetTests.cs": "public int Value;\n" * 120,
        "tools/check.py": "print('ok')\n",
        "README.md": "# Budget application\n",
        "Budget.csproj": '<Project Sdk="Microsoft.NET.Sdk"/>\n',
    }
    for name, text in files.items():
        path = repo / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    row = scan(repo, tmp_path / "out", anonymize=False)
    with zipfile.ZipFile(tmp_path / "out" / row["sample_quality"]["zip_path"]) as archive:
        manifest = json.loads(archive.read("data/regression/sample_manifest.json"))
        paths = {item["path"] for item in manifest["files"]}
        inner = json.loads(archive.read("data/regression/metadata.json"))
    assert paths == set(files) - {"src/reports/DataSet.Designer.cs"}
    assert row["autogen_loc"] == 10000
    assert inner["sample_loc"] == row["sample_loc"] == sum(item["code_loc"] for item in manifest["files"])
    assert row["sample_quality"]["counted_after_anonymization"]
    stats = collect_file_stats(repo)
    assert [s.rel for s in select_sample_files(stats, "C#")] == [s.rel for s in select_sample_files(list(reversed(stats)), "C#")]


