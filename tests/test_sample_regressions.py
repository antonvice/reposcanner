@pytest.mark.skipif(not shutil.which("dotnet"), reason=".NET SDK is not installed")
def test_anonymized_csharp_compiles_with_interpolated_and_raw_strings(tmp_path):
    sdks = subprocess.run(["dotnet", "--list-sdks"], check=True, capture_output=True, text=True).stdout.splitlines()
    if not sdks:
        pytest.skip("No .NET SDK")
    major = int(sdks[-1].split(".")[0])
    if major < 7:
        pytest.skip("C# raw strings require .NET 7 or newer")
    source = '''namespace AcmeCorp;
public class Budget {
    private bool ShouldSerializeTABLE_VILSAIF_1_MAINTABLE21() { return false; }
    string GetName(string value) => value;
    string Label() => $"https://private.example/{GetName("AcmeCorp")}/{ShouldSerializeTABLE_VILSAIF_1_MAINTABLE21()}";
    string Verbatim() => $@"https://private.example/{GetName("AcmeCorp")}";
    string Raw() => $$"""https://private.example/{{GetName("AcmeCorp")}}""";
    string PlainRaw() => """https://private.example""";
    string Password = "short";
}'''
    (tmp_path / "Budget.cs").write_text(RepoAnonymizer(enabled=True, terms=["AcmeCorp"]).sanitize_code(source, Path("Budget.cs")))
    (tmp_path / "Budget.csproj").write_text(
        f'<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><TargetFramework>net{major}.0</TargetFramework></PropertyGroup></Project>'
    )
    (tmp_path / "NuGet.Config").write_text("<configuration><packageSources><clear /></packageSources></configuration>")
    env = dict(os.environ, DOTNET_CLI_HOME=str(tmp_path / "dotnet-home"), DOTNET_CLI_TELEMETRY_OPTOUT="1")
    result = subprocess.run(
        ["dotnet", "build", "--nologo", "--verbosity", "quiet"], cwd=tmp_path, env=env, capture_output=True, text=True, timeout=60
    )
    assert result.returncode == 0, result.stdout + result.stderr
