def test_anonymization_preserves_long_identifiers_decorators_versions_and_python_syntax():
    text = """@decorator
def ShouldSerializeTABLE_VILSAIF_1_MAINTABLE21():
    version = "1.2.3.4"
    password = "short"
    endpoint = "https://private.example/v1"
    return f"{endpoint}/{ShouldSerializeTABLE_VILSAIF_1_MAINTABLE21.__name__}"
"""
    result = RepoAnonymizer(enabled=True).sanitize_code(text, Path("app.py"))
    ast.parse(result)
    assert "@decorator" in result
    assert result.count("ShouldSerializeTABLE_VILSAIF_1_MAINTABLE21") == 2
    assert '"1.2.3.4"' in result
    assert '"short"' not in result
    assert "private.example" not in result


def test_csharp_interpolation_and_long_identifiers_are_preserved():
    text = """class Budget {
    private bool ShouldSerializeTABLE_VILSAIF_1_MAINTABLE21() { return false; }
    string GetName(string value) => value;
    string Label() => $"https://private.example/{GetName("AcmeCorp")}/{ShouldSerializeTABLE_VILSAIF_1_MAINTABLE21()}";
    string Verbatim() => $@"https://private.example/{GetName("AcmeCorp")}";
}"""
    result = RepoAnonymizer(enabled=True, terms=["AcmeCorp"]).sanitize_code(text, Path("Budget.cs"))
    assert "private bool ShouldSerializeTABLE_VILSAIF_1_MAINTABLE21()" in result
    assert '{GetName("ANON_ORG_001")}' in result
    assert "{ShouldSerializeTABLE_VILSAIF_1_MAINTABLE21()}" in result
    assert "private.example" not in result
    assert "AcmeCorp" not in result


@pytest.mark.parametrize(
    ("filename", "text"),
    [
        ("Client.java", '@Override\npublic String getName() { return "https://private.example"; }'),
        ("client.ts", 'const x = `https://private.example/${getName("AcmeCorp")}`;'),
        ("client.go", 'package client\nvar endpoint = "https://private.example"\n'),
        ("client.rs", '#[derive(Debug)]\nstruct Client;\nconst URL: &str = "https://private.example";'),
        ("client.rb", 'endpoint = "https://private.example"\n'),
    ],
)
def test_other_language_code_tokens_do_not_change(filename, text):
    anon = RepoAnonymizer(enabled=True)
    result = anon.sanitize_code(text, Path(filename))
    lexer = get_lexer_for_filename(filename)

    def code_tokens(source):
        return [(kind, value) for _, kind, value in lexer.get_tokens_unprocessed(source) if kind not in String and kind not in Comment]

    assert code_tokens(text) == code_tokens(result)
    assert "private.example" not in result


def test_aliases_are_consistent_across_files_paths_and_case_sensitive_secrets():
    anon = RepoAnonymizer(enabled=True, terms=["AcmeCorp"])
    one = anon.sanitize_code(
        'namespace AcmeCorp { class App { string owner = "AcmeCorp"; string password = "SameSecret"; } }', Path("App.cs")
    )
    two = anon.sanitize_code('string owner = "AcmeCorp"; string password = "SameSecret"; string token = "samesecret";', Path("Other.cs"))
    assert "namespace ANON_ORG_001" in one
    assert '"ANON_ORG_001"' in one and '"ANON_ORG_001"' in two
    assert '"ANON_SECRET_001"' in one and '"ANON_SECRET_001"' in two
    assert '"ANON_SECRET_002"' in two
    assert anon.sanitize_path("AcmeCorp/AcmeCorp.cs") == "ANON_ORG_001/ANON_ORG_001.cs"
    assert anon.report()["unique_replacements_by_tag"]["SECRET"] == 2
    assert "SameSecret" not in json.dumps(anon.report())


def test_client_archive_has_no_identity_in_paths_metadata_or_source(tmp_path):
    repo = tmp_path / "repo"
    repo.mkdir()
    (repo / "AcmeCorp.py").write_text('class AcmeCorp:\n    password = "short"\n')
    row = scan(repo, tmp_path / "out", anonymization_terms=["AcmeCorp"], description="AcmeCorp budgeting")
    with zipfile.ZipFile(tmp_path / "out" / row["sample_quality"]["zip_path"]) as archive:
        for name in archive.namelist():
            assert "AcmeCorp" not in name
            content = archive.read(name).decode()
            assert "AcmeCorp" not in content
            assert '"short"' not in content
            if name.endswith(".json"):
                json.loads(content)
            if name.endswith(".py"):
                ast.parse(content)


