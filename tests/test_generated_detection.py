import json
import subprocess
import sys
import tomllib
import zipfile
from pathlib import Path

import pytest

from reposcanner.scanner import METADATA_COLUMNS, build_metadata, generated_file_reason


def scan(repo, **options):
    return build_metadata(repo, "generated-review", include_sale_prediction=False, **options)


def test_percentage_is_loc_weighted_with_explicit_denominator_and_language_breakdown(tmp_path):
    (tmp_path / "Client.generated.cs").write_text("// <auto-generated>\n" + "int generated;\n" * 100)
    (tmp_path / "Rules.cs").write_text("int authored;\n" * 300)
    (tmp_path / "reports.xml").write_text("<row/>\n" * 600)
    row = scan(tmp_path)
    report = row["generated_code_detection"]
    assert row["logical_loc"] == report["total_loc"] == 1000
    assert row["autogen_loc"] == report["generated_loc"] == 100
    assert row["generated_code_percent"] == report["percent"] == 10.0
    assert report["by_language"]["C#"] == {"total_loc": 400, "generated_loc": 100, "percent": 25.0}
    assert report["by_language"]["XML"]["percent"] == 0.0
    assert report["files"] == [{"path": "Client.generated.cs", "language": "C#", "code_loc": 100, "reason": "generated_filename"}]
    assert "gate" not in report and not any(key.startswith("ai_") for key in row)


def test_generated_report_inspects_all_counted_files_and_uses_scan_exclusions(tmp_path):
    for i in range(25):
        (tmp_path / f"Model{i}.g.cs").write_text("int value;\n")
    (tmp_path / "Rules.cs").write_text("int value;\n" * 25)
    (tmp_path / "node_modules").mkdir()
    (tmp_path / "node_modules" / "ignored.generated.js").write_text("let x;\n" * 1000)
    report = scan(tmp_path)["generated_code_detection"]
    assert report["total_files"] == 26
    assert report["generated_files"] == len(report["files"]) == 25
    assert report["generated_loc"] == 25 and report["total_loc"] == 50 and report["percent"] == 50.0


@pytest.mark.parametrize("filename", ["Cargo.lock", "go.sum", "poetry.lock", "Pipfile.lock", "composer.lock", "uv.lock", "yarn.lock"])
def test_known_generated_manifests_are_counted_and_excluded_from_samples(tmp_path, filename):
    (tmp_path / filename).write_text("value = 1\n")
    row = scan(tmp_path, prep_sample=True, sample_output=str(tmp_path / "output"))
    assert row["generated_code_percent"] == 100.0
    assert row["generated_code_detection"]["files"][0]["reason"] == "generated_manifest_or_lockfile"
    assert row["sample_quality"]["selected_files"] == 0
    assert row["sample_quality"]["status"].startswith("FAIL")


@pytest.mark.parametrize("content", [None, "", "# comments only\n"])
def test_zero_denominator_is_unknown_instead_of_zero_generated(tmp_path, content):
    if content is not None:
        (tmp_path / "empty.py").write_text(content)
    row = scan(tmp_path)
    assert row["generated_code_percent"] is None
    assert row["generated_code_detection"]["percent"] is None
    assert row["generated_code_detection"]["status"] == "no_counted_code"


def test_no_matches_means_zero_detected_not_certified_human(tmp_path):
    (tmp_path / "rules.py").write_text("print(1)\n")
    row = scan(tmp_path)
    assert row["generated_code_percent"] == 0.0
    assert row["generated_code_detection"]["generated_files"] == 0
