@pytest.mark.parametrize(
    ("path", "source", "reason"),
    [
        ("generated/rules.py", "print(1)\n", "generated_directory"),
        ("rules.py", "# Code generated by a tool. DO NOT EDIT.\nprint(1)\n", "generated_comment_header"),
        ("Model.java", '@Generated("tool")\nclass Model {}', "generated_annotation"),
        ("Rules.py", "# Do not edit production records manually.\ndef update(): pass\n", None),
    ],
)
def test_reasons_describe_tool_evidence_without_treating_a_warning_as_generation(path, source, reason):
    assert generated_file_reason(Path(path), path, source) == reason


def test_zip_and_external_metadata_agree_and_generated_paths_are_anonymized(tmp_path):
    repo = tmp_path / "repo"
    repo.mkdir()
    (repo / "AcmeCorp.Designer.cs").write_text("int generated;\n")
    (repo / "Rules.cs").write_text("int value;\n")
    row = scan(repo, prep_sample=True, sample_output=str(tmp_path / "out"), anonymization_terms=["AcmeCorp"])
    with zipfile.ZipFile(tmp_path / "out" / row["sample_quality"]["zip_path"]) as archive:
        inner = json.loads(archive.read("data/generated-review/metadata.json"))
        manifest = json.loads(archive.read("data/generated-review/sample_manifest.json"))
        assert not any(name.endswith("Designer.cs") for name in archive.namelist())
    assert inner["generated_code_detection"] == row["generated_code_detection"]
    assert inner["generated_code_percent"] == row["generated_code_percent"] == 50.0
    assert "AcmeCorp" not in json.dumps(row)
    assert manifest["sample_quality"]["excluded_generated_loc"] == 1
    assert manifest["format_version"] == 3


def test_default_cli_and_core_output_work_without_ai_flags_or_models(tmp_path):
    (tmp_path / "Rules.cs").write_text("int value;\n")
    (tmp_path / "Model.g.cs").write_text("int generated;\n")
    for schema in ("core", "extended"):
        result = subprocess.run(
            [sys.executable, "-m", "reposcanner", str(tmp_path), "--schema", schema, "--output", "-", "--no-prep-sample", "--no-hud"],
            capture_output=True,
            text=True,
            check=True,
        )
        row = json.loads(result.stdout)
        assert row["generated_code_percent"] == 50.0
        assert not any(key.startswith("ai_") for key in row)
        if schema == "core":
            assert set(row) == set(METADATA_COLUMNS) and len(row) == 31


@pytest.mark.parametrize("option", ["--ai-detect", "--no-ai-detect", "--ai-model", "--ai-threshold"])
def test_removed_ai_options_are_rejected_instead_of_silently_ignored(option):
    result = subprocess.run([sys.executable, "-m", "reposcanner", option], capture_output=True, text=True)
    assert result.returncode == 2 and "unrecognized arguments" in result.stderr


def test_model_dependencies_are_removed_from_project_and_lockfile():
    repo = Path(__file__).resolve().parents[1]
    project = tomllib.loads((repo / "pyproject.toml").read_text())
    lock = tomllib.loads((repo / "uv.lock").read_text())
    assert "ai" not in project["project"].get("optional-dependencies", {})
    forbidden = {"torch", "transformers", "huggingface-hub", "accelerate", "safetensors", "tokenizers", "triton"}
    assert not forbidden.intersection(package["name"] for package in lock["package"])
